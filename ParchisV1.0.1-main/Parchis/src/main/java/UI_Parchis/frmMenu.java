    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        String nombreJ1 = JOptionPane.showInputDialog(this, "Ingrese el nombre del Jugador 1 (Rojo):", "Registro de Jugadores", JOptionPane.QUESTION_MESSAGE);
        if (nombreJ1 == null || nombreJ1.trim().isEmpty()) {
            nombreJ1 = "Jugador 1";
        }

        String nombreJ2 = JOptionPane.showInputDialog(this, "Ingrese el nombre del Jugador 2 (Amarillo):", "Registro de Jugadores", JOptionPane.QUESTION_MESSAGE);
        if (nombreJ2 == null || nombreJ2.trim().isEmpty()) {
            nombreJ2 = "Jugador 2";
        }

        // 2. Crear las entidades de los jugadores registrados
        List<Jugador> jugadores = new ArrayList<>();
        jugadores.add(new Jugador(1, nombreJ1.trim(), "Rojo"));
        jugadores.add(new Jugador(2, nombreJ2.trim(), "Amarillo"));

        // 3. Crear el subsistema de reglas de negocio utilizando el patrón Fachada (Objeto Mock)
        ReglasParchis fachadaMock = new ReglasParchisMock(jugadores);

        // 4. Instanciar el Modelo MVC (comunicándose con la Fachada)
        ParchisModelo modelo = new ParchisModelo(fachadaMock);

        // 5. Instanciar y mostrar el tablero
      frmTablero verTablero = new frmTablero(modelo);
        verTablero.setVisible(true);

        // 6. Cerrar el menú principal
        this.dispose();
    
    }//GEN-LAST:event_btnIniciarActionPerformed

